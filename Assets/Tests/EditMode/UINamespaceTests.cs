using System;
using System.IO;
using System.Reflection;
using Client.Framework.UI;
using NUnit.Framework;
using UnityEngine;

namespace Client.Tests.EditMode
{
    [Category("U5")]
    public sealed class UINamespaceTests
    {
        GameObject root; string directory, hand, output;
        Type Generator => UIAuthoringTests.Tool("UIBindingGenerator");
        [SetUp] public void Setup()
        {
            UnityEditor.AssetDatabase.DisallowAutoRefresh();
            root = new GameObject("UINamespaceFixture", typeof(RectTransform), typeof(UIBindings));
            directory = "Assets/Scripts/Game/NamespaceFixture" + Guid.NewGuid().ToString("N");
            Directory.CreateDirectory(directory + "/Generated");
            hand = directory + "/UINamespaceFixture.cs";
            output = directory + "/Generated/UINamespaceFixture.G.Bindings.cs";
        }
        [TearDown] public void Cleanup()
        {
            UnityEngine.Object.DestroyImmediate(root);
            if (!Path.GetFullPath(directory).StartsWith(Path.GetFullPath("Assets/Scripts/Game/NamespaceFixture"), StringComparison.OrdinalIgnoreCase)) throw new InvalidOperationException();
            UnityEditor.AssetDatabase.DeleteAsset(directory);
            if (Directory.Exists(directory)) Directory.Delete(directory, true);
            UnityEditor.AssetDatabase.AllowAutoRefresh();
        }
        object Generate(string ns) => Generator.GetMethod("Generate").Invoke(null, new object[] { root.GetComponent<UIBindings>(), ns, "UINamespaceFixture", output });
        static bool Success(object r) => (bool)r.GetType().GetProperty("Success").GetValue(r);
        [TestCase("Client.Game")]
        [TestCase("Client.Game.Login")]
        public void MatchingPartialNamespacePreservesHandAndIsIdempotent(string ns)
        {
            byte[] bytes = System.Text.Encoding.UTF8.GetBytes("namespace " + ns + " { public sealed partial class UINamespaceFixture { public int Keep => 7; } }\n");
            File.WriteAllBytes(hand, bytes);
            Assert.That(Success(Generate(ns)), Is.True);
            var generated = File.ReadAllBytes(output); var time = File.GetLastWriteTimeUtc(output);
            Assert.That(File.ReadAllText(output), Does.Contain("namespace " + ns + "\n"));
            Assert.That(Success(Generate(ns)), Is.True);
            Assert.That(File.ReadAllBytes(output), Is.EqualTo(generated));
            Assert.That(File.GetLastWriteTimeUtc(output), Is.EqualTo(time));
            Assert.That(File.ReadAllBytes(hand), Is.EqualTo(bytes));
        }
        [TestCase("Other.Game.Login")][TestCase("Client.Game.class")][TestCase("Client.Game..Login")]
        [TestCase("Client.Game.Login-Bad")][TestCase("Client.Game.")][TestCase("Client.Game.Login.Other")]
        public void InvalidOrMismatchingNamespaceDoesNotMutateOldBytes(string ns)
        {
            File.WriteAllText(hand, "namespace Client.Game.Login { public sealed partial class UINamespaceFixture {} }");
            File.WriteAllText(output, "old generated bytes");
            string before = File.ReadAllText(hand);
            Assert.That(Success(Generate(ns)), Is.False);
            Assert.That(File.ReadAllText(output), Is.EqualTo("old generated bytes"));
            Assert.That(File.ReadAllText(hand), Is.EqualTo(before));
        }
        [Test] public void LoginFolderDefaultsToBindingSpecNamespace()
        {
            var method = Generator.GetMethod("NamespaceFor");
            Assert.That(method, Is.Not.Null, "Creator must derive the feature namespace.");
            Assert.That(method.Invoke(null, new object[] { "Assets/Content/UI/Login" }), Is.EqualTo("Client.Game.Login"));
        }
    }
}
