#requires -Version 7.0
[CmdletBinding()]param()
$ErrorActionPreference='Stop'
$project=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
. (Join-Path $project 'Tool/Client/Framework-Evidence.ps1')
. (Join-Path $project 'Tool/Client/Framework-IO.ps1')
$source=Join-Path $project 'Tests/Fixtures/Delivery'
$run=Join-Path $project ('Builds/Tests/D2/ThrowFixture-'+[Guid]::NewGuid().ToString('N'));New-Item -ItemType Directory -Path $run|Out-Null
$records=@()
function Check([string]$Name,[scriptblock]$Body){try{&$Body;$script:records+=@{name=$Name;passed=$true};Write-Host "D2_THROW_FIXTURE_PASS $Name"}catch{$script:records+=@{name=$Name;passed=$false;error=$_.Exception.Message};Write-Host "D2_THROW_FIXTURE_FAIL $Name $($_.Exception.Message)"}}
function Require($Value,[string]$Message){if(-not $Value){throw $Message}}
Check 'test overlay preserves original V2 generated bytes and probe body' {
    $result=Assert-FrameworkThrowFixture $source
    Require ($result.passed -and $result.unityCompilation -ceq 'NotRun' -and $result.generatedByteIdentical) 'Throw provenance did not verify.'
}
foreach($mode in @('generated','probe','marker')){
    Check "reject $mode drift" {
        $fixture=Join-Path $run $mode;New-Item -ItemType Directory -Path $fixture|Out-Null
        Copy-Item -LiteralPath (Join-Path $source 'throw-provenance.json'),(Join-Path $source 'provenance.json') -Destination $fixture
        $contract=Read-FrameworkJson (Join-Path $source 'throw-provenance.json')
        foreach($file in $contract.files){$destination=Join-Path $fixture $file.path;[IO.Directory]::CreateDirectory((Split-Path -Parent $destination))|Out-Null;Copy-Item -LiteralPath (Join-Path $source $file.path) -Destination $destination}
        if($mode -eq 'marker'){$contract.markerCode='F8_THROW';$contract|ConvertTo-Json -Depth 8|Set-Content -LiteralPath (Join-Path $fixture 'throw-provenance.json') -Encoding utf8NoBOM}
        else{$relative=if($mode -eq 'generated'){'ThrowOnStart/Assets/Scripts/Game/Protocol/Delivery/Added.cs'}else{'ThrowOnStart/Assets/Scripts/Game/DeliveryVersion.cs'};Add-Content -LiteralPath (Join-Path $fixture $relative) -Value '// drift'}
        $rejected=$false;try{Assert-FrameworkThrowFixture $fixture|Out-Null}catch [IO.InvalidDataException]{$rejected=$true};Require $rejected 'Mutated throw artifact was accepted.'
    }
}
$failed=@($records|Where-Object passed -eq $false)
Write-FrameworkJsonNew (Join-Path $run 'test-result.json') @{schemaVersion=1;evidenceKind='SyntheticUnit';nativeAcceptance=$false;passed=($failed.Count -eq 0);cases=$records;unityCompilation='NotRun';fixtureContractSha256=(Get-FrameworkFileHash (Join-Path $source 'throw-provenance.json'))}
Write-Host "D2_THROW_FIXTURE_RECEIPT $run"
if($failed.Count){throw "D2_THROW_FIXTURE_FAILED $($failed.Count)/$($records.Count)"}
